"""
Plate/measurement DB-tracking business logic — bridges "a SiLA2 command just
succeeded" to "here is what to write to the chemical database tables"
(src/database.py). Shared between the workflow-execution path
(webapp/routes/workflows.py::_execute_step) and the manual/direct command
path (webapp/routes/instruments.py::execute_device_command), so a measurement
or recipe execution is tracked identically regardless of how it was launched.

This module is intentionally in src/, not webapp/, so both routers can
import it without a circular dependency. src/database.py stays a pure
persistence layer (SQL in, dicts out); this module owns the filesystem/
recipe/HAL parsing and SiLA2-result-shape knowledge.
"""

from __future__ import annotations

import json
import logging
import re
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, List, Optional

# Every timestamp in this module is deliberately datetime.now() (naive LOCAL
# time), matching the convention used everywhere else timestamps are stored
# in this app (webapp/routes/*.py, models.py) - NOT datetime.utcnow(). The
# webapp's date-formatting helpers (e.g. database.html's fmtDate()) build a
# plain JS `Date` from these ISO strings, which - with no "Z"/offset suffix -
# JS parses as LOCAL time already. A naive UTC timestamp stored here would
# silently display off by the local UTC offset (confirmed on hardware: a
# plate's displayed "prepared on" time was ~2h behind its own plate_id's
# embedded timestamp, which already correctly used local time).

try:
    from src import database as _db
except ImportError:
    _db = None

logger = logging.getLogger(__name__)

# Matches the fixed-format timestamp TecanBridge.cs appends to every AnIML
# filename: f"{cleanPlateId}_{timestamp:yyyyMMdd_HHmmss}.animl". Stripping
# this recovers the effective plate id the bridge actually used, whether it
# was supplied by the caller (sanitized: spaces->_, slashes->-) or
# auto-generated by plate_reader_impl.py as "{protocol_slug}_{timestamp}"
# when the caller left PlateID empty. See TecanBridge.cs ~line 525.
_ANIML_TIMESTAMP_SUFFIX_RE = re.compile(r'_\d{8}_\d{6}$')


def _resolve_source_path(animl_path: str) -> Path:
    """Given a Results/AnIML/<name>.animl path, return the sibling
    Results/XML/<name>.xml it was generated from, if it exists - both are
    guaranteed to share the same filename stem, since TecanBridge.cs builds
    both paths from the same `baseName` in the same call
    (result.XmlFilePath / result.AnIMLFilePath, TecanBridge.cs ~line
    536-539). Falls back to the given path unchanged (parsed as AnIML) when
    no sibling XML is present - e.g. an .animl kept without its source XML,
    or a path that's already a .xml itself."""
    p = Path(animl_path)
    if p.suffix.lower() == ".xml":
        return p
    candidate = p.parent.parent / "XML" / (p.stem + ".xml")
    return candidate if candidate.exists() else p


# ─────────────────────────────────────────────────────────────────────────────
#  Shared plate-definition lookup (fixes the "?×?" dimensions bug: a HAL
#  config's LoadName doesn't always match the labware JSON's filename, only
#  its internal "id" field)
# ─────────────────────────────────────────────────────────────────────────────

def find_plate_definition(plates_dir: Path, load_name: str) -> Optional[Dict[str, Any]]:
    """Find a Library/Labware/Plates/*.plate.json by internal `id` field OR
    filename stem — mirrors webapp/routes/instruments.py's GET
    /api/library/plates/{plate_id}, which already had to solve this because
    filenames don't always match a labware's `opentrons_load_name`/HAL
    LoadName (e.g. corning_24_wellplate_3400ul_flat.plate.json has
    "id": "corning_24_wellplate_3.4ml_flat")."""
    if not plates_dir.exists():
        return None
    for f in plates_dir.glob("*.plate.json"):
        try:
            data = json.loads(f.read_text(encoding="utf-8-sig"))
            if data.get("id") == load_name or f.stem.replace(".plate", "") == load_name:
                return data
        except Exception:
            continue
    return None


def _resolve_plate_metadata(base_dir: Path) -> Dict[str, Any]:
    """Read the active HAL config, find the primary well-plate labware, and
    return its metadata (dimensions, volumes, etc.) plus which HAL slot it's
    in. Returns {} if nothing resolvable — callers must not treat this as an
    error, just "dimensions unknown"."""
    try:
        active_file = base_dir / "Library" / "HardwareConfig" / ".active"
        hal_name = active_file.read_text(encoding="utf-8-sig").strip() if active_file.exists() else ""
        if not hal_name:
            return {}
        hal_path = base_dir / "Library" / "HardwareConfig" / hal_name
        if not hal_path.exists():
            hal_path = base_dir / "Library" / "HardwareConfig" / f"{hal_name}.json"
        if not hal_path.exists():
            return {}
        hal = json.loads(hal_path.read_text(encoding="utf-8-sig"))
        plates_dir = base_dir / "Library" / "Labware" / "Plates"
        for logical, lw in hal.get("Labware", {}).items():
            load_name = lw.get("LoadName", "")
            if "wellplate" not in load_name.lower():
                continue
            slot = lw.get("Slot", "")
            meta = find_plate_definition(plates_dir, load_name)
            if meta:
                # NOTE: deliberately NOT setting "display_name" here. The
                # plates table's display_name column is a user-editable
                # per-instance nickname (see database.py's schema comment and
                # update_plate()) - it used to get pre-filled with the
                # LABWARE TYPE's own display_name (e.g. "Corning 96 Well
                # Plate 360 uL Flat", from this .plate.json's own
                # "display_name" field), which made every freshly-prepared
                # plate's title just say what kind of physical plate it is
                # instead of which one - already covered by "plate_type"
                # below (technical load name) and shown separately in the UI.
                # Leaving it unset lets the frontend fall back to
                # recipe_name (which already carries the recipe+timestamp)
                # until a human actually renames the plate.
                return {
                    "plate_type": load_name,
                    "rows": meta.get("rows"),
                    "columns": meta.get("columns"),
                    "total_wells": meta.get("total_wells"),
                    "max_volume_ul": meta.get("max_volume_ul"),
                    "working_volume_ul": meta.get("working_volume_ul"),
                    "well_shape": meta.get("well_shape"),
                    "well_depth_mm": meta.get("well_depth_mm"),
                    "bottom_type": meta.get("bottom_type"),
                    "brand": meta.get("brand"),
                    "tecan_compatible": meta.get("tecan_compatible", True),
                    "labware_slot": slot,
                    "hal_config": hal_name.replace(".json", ""),
                }
            return {"plate_type": load_name, "labware_slot": slot,
                     "hal_config": hal_name.replace(".json", "")}
    except Exception as exc:
        logger.warning(f"HAL metadata resolution failed: {exc}")
    return {}


def _extract_wells_from_recipe(recipe_name: str, plate_id: str, base_dir: Path) -> List[Dict[str, Any]]:
    """
    Parse recipe JSON to build per-well records with reagent, volume,
    liquid_class, phase_name (from Comment steps used as group markers), and
    pipette_mount.

    Supports: Transfer, TransferWithLiquidClass, Distribute, Aspirate→Dispense
    pairs. Keyed by (well_id, reagent_name) so a well receiving two different
    reagents gets two rows instead of the second overwriting the first (the
    previous bug — the wells table itself already allows multiple reagents
    per well via UNIQUE(plate_id, well_id, reagent_name), the accumulator
    here just wasn't using that key shape).
    """
    try:
        recipe_path = base_dir / "Library" / "Recipes" / f"{recipe_name}.json"
        if not recipe_path.exists():
            return []
        recipe = json.loads(recipe_path.read_text(encoding="utf-8-sig"))
        steps = recipe.get("Steps", [])
        now = datetime.now().isoformat()

        # Reverse index: "Source_1:A1" -> "GEL-N3". Recipes generated with the
        # generic numbered-source convention (Source_1, Source_2, ...) never
        # put the real reagent name in a Distribute/Transfer step's "Source"
        # field - that field is always "Source_N:well". Naively taking its
        # prefix (the old behaviour here) gives "Source_1", not the actual
        # chemical - Metadata.WellAssignments (built alongside
        # ReagentMapping in excel_recipe_parser.py, e.g. "Source_1:A1+A3" for
        # a reagent with backup wells) is the only place that maps a specific
        # well back to which reagent it holds.
        source_well_to_reagent: Dict[str, str] = {}
        for reagent, spec in recipe.get("Metadata", {}).get("WellAssignments", {}).items():
            if ":" not in spec:
                continue
            source_key, wells_part = spec.split(":", 1)
            for well in wells_part.split("+"):
                if well:
                    source_well_to_reagent[f"{source_key}:{well}"] = reagent

        well_records: Dict[tuple, Dict[str, Any]] = {}
        current_phase = "default"
        current_source = ""
        current_volume = 0.0
        current_liquid_class = ""
        current_pipette = recipe.get("Pipettes", {}).get("left") and "left" or "left"

        _transfer_cmds = {
            "Transfer", "TransferWithLiquidClass", "Distribute",
            "Aspirate", "Dispense",
        }

        for step in steps:
            cmd = step.get("Command", "")

            if cmd == "Comment":
                msg = step.get("Message", step.get("Text", "")).strip()
                if msg:
                    current_phase = msg
                continue

            if cmd == "Delay":
                current_phase = "default"
                continue

            if cmd not in _transfer_cmds:
                continue

            pipette_mount = step.get("PipetteMount", current_pipette)
            liquid_class = step.get("LiquidClass", current_liquid_class) or ""
            source = step.get("Source", current_source)
            raw_volume = step.get("Volume", current_volume)

            # Distribute supports a per-destination Volume LIST (e.g. a
            # combinatorial dilution series with a different volume per well)
            # as an alternative to the usual single scalar applied to every
            # destination - see excel_recipe_parser.py's Distribute branch,
            # which emits exactly this shape. float(list) raises, and the
            # try/except around this whole function used to swallow that
            # silently, losing well data for the ENTIRE recipe (not just the
            # step with the list) - resolve per-destination below instead of
            # collapsing to a single scalar up front.
            volume_is_list = isinstance(raw_volume, (list, tuple))
            # Only meaningful in the scalar case - a per-destination volume is
            # resolved separately, per dest_idx, in the loop below.
            volume = 0.0 if volume_is_list else float(raw_volume or 0)

            if cmd == "Aspirate":
                current_source = source
                current_volume = 0.0 if isinstance(raw_volume, (list, tuple)) else raw_volume
                current_liquid_class = liquid_class
                continue

            if cmd == "Dispense":
                source = source or current_source
                if not volume_is_list and not volume:
                    volume = float(current_volume or 0)
                liquid_class = liquid_class or current_liquid_class

            destinations = step.get("Destinations") or step.get("Destination") or step.get("Dest") or []
            if isinstance(destinations, str):
                destinations = [destinations]

            # "Source" can also be a liquid-fallback candidate LIST (Transfer/
            # Distribute + VerifyLiquid + backup wells - see
            # protocol_generator.py's runtime fallback branch). All candidates
            # belong to the same reagent by construction, so the first one is
            # enough to resolve which reagent this is; keep the full "+"-joined
            # form for display so it's clear backup wells were in play.
            source_candidates = source if isinstance(source, list) else [source]
            source = "+".join(source_candidates)
            first_candidate = source_candidates[0] if source_candidates else ""

            reagent_name = (
                source_well_to_reagent.get(first_candidate)
                or (first_candidate.split(":")[0] if ":" in first_candidate else first_candidate)
            )

            for dest_idx, dest in enumerate(destinations):
                if not dest or ":" not in dest:
                    continue
                labware, well_id = dest.split(":", 1)
                well_id = well_id.strip()
                if not well_id:
                    continue
                row_label = well_id[0].upper()
                col_str = well_id[1:]
                col_num = int(col_str) if col_str.isdigit() else 0

                dest_volume = float(raw_volume[dest_idx] or 0) if volume_is_list and dest_idx < len(raw_volume) else volume

                key = (well_id, reagent_name)
                if key in well_records:
                    well_records[key]["volume_ul"] += dest_volume
                else:
                    well_records[key] = {
                        "plate_id": plate_id,
                        "well_id": well_id,
                        "row_label": row_label,
                        "col_number": col_num,
                        "reagent_name": reagent_name,
                        "volume_ul": dest_volume,
                        "concentration_mm": None,
                        "liquid_class": liquid_class,
                        "phase_name": current_phase,
                        "source_well": source,
                        "pipette_mount": pipette_mount,
                        "pipetted_at": now,
                    }

        return list(well_records.values())
    except Exception as exc:
        logger.warning(f"Recipe well extraction failed: {exc}")
        return []


def _apply_concentrations(wells: List[Dict[str, Any]]) -> None:
    """Mutate `wells` in place: set concentration_mm = stock_concentration_mm
    * volume_ul / total_volume_in_well when the reagent's stock concentration
    is registered in reagent_catalog and the well's total volume is known.
    Left None otherwise — never fabricate a value."""
    if not wells or _db is None:
        return
    try:
        stock_by_reagent = {
            r["name"]: r["stock_concentration_mm"]
            for r in _db.get_reagents()
            if r.get("stock_concentration_mm")
        }
    except Exception as exc:
        logger.warning(f"Could not load reagent stock concentrations: {exc}")
        return
    if not stock_by_reagent:
        return
    totals: Dict[str, float] = {}
    for w in wells:
        totals[w["well_id"]] = totals.get(w["well_id"], 0.0) + (w.get("volume_ul") or 0.0)
    for w in wells:
        stock = stock_by_reagent.get(w.get("reagent_name"))
        total = totals.get(w["well_id"])
        if stock and total:
            w["concentration_mm"] = stock * (w.get("volume_ul") or 0.0) / total


def ensure_plate_for_measurement(plate_id: str, *, run_id: Optional[str] = None,
                                   notes: Optional[str] = None) -> None:
    """Guarantee a `plates` row exists for plate_id — every measurement
    (manual or workflow-driven) must be traceable to a plate record, even
    with no prior pipetting step. No-ops if the plate already exists, so it
    never clobbers the richer metadata an earlier ExecuteRecipe-driven
    save_plate() call may have already written for this plate_id."""
    if _db is None or not plate_id:
        return
    try:
        if _db.get_plate(plate_id) is not None:
            return
        _db.save_plate({
            "plate_id": plate_id,
            "run_id": run_id,
            "status": "measured",
            "prepared_at": datetime.now().isoformat(),
            "notes": notes or (
                "No pipetting record - plate created from a manual/direct measurement."
            ),
        })
    except Exception as exc:
        logger.warning(f"Failed to ensure plate row for '{plate_id}': {exc}")



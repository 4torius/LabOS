def track_opentrons_recipe(
    device_id: str, action: str, params: dict, result, *,
    run_id: Optional[str], base_dir: Optional[Path], state=None,
) -> Optional[str]:
    """Called after a successful Opentrons command. If it was a recipe
    execution, creates the plates/wells DB records and returns the new
    plate_id (or None if this wasn't a recipe-execution command)."""
    if "opentrons" not in device_id.lower() or action not in ("ExecuteRecipe", "RunRecipe", "run_recipe"):
        return None

    recipe_name = params.get("RecipeName") or params.get("recipe_name") or params.get("recipe", "")
    recipe_slug = re.sub(r'[^a-z0-9]', '', recipe_name.lower())[:12] if recipe_name else "unknown"
    plate_id = f"PLT-{datetime.now().strftime('%Y%m%d-%H%M%S')}-{recipe_slug}"

    if state is not None:
        state.add_log("info", f"Plate ID: {plate_id}", "workflow")

    if _db is not None:
        try:
            plate_meta = _resolve_plate_metadata(base_dir) if base_dir else {}
            wells = _extract_wells_from_recipe(recipe_name, plate_id, base_dir) if base_dir else []
            _apply_concentrations(wells)
            _db.save_plate({
                "plate_id": plate_id,
                "run_id": run_id,
                "recipe_name": recipe_name,
                "prepared_at": datetime.now().isoformat(),
                "status": "prepared",
                **plate_meta,
            })
            if wells:
                _db.save_wells(wells)
        except Exception as exc:
            logger.warning(f"Plate DB save failed: {exc}")

    if state is not None:
        state.add_log("info", f"Pipetting recorded for plate {plate_id}", "plates")

    return plate_id


def track_tecan_measurement(
    device_id: str, action: str, params: dict, result, *,
    run_id: Optional[str], current_plate_id: Optional[str], base_dir: Optional[Path], state=None,
) -> Optional[str]:
    """Called after a successful Tecan command. If it was a measurement,
    resolves the effective plate_id (see _ANIML_TIMESTAMP_SUFFIX_RE), ensures
    a plate row exists for it (bug: manual measurements never reached the DB
    before), writes an instrument_measurements row eagerly (fixes
    animl_path always being NULL and the measurement_id race — see
    database.save_run()'s docstring), and stores per-well values. Returns
    the plate_id used, or None if this wasn't a measurement command."""
    if "tecan" not in device_id.lower() or action not in ("RunMeasurement", "RunAnalysis"):
        return None

    result_data = result.data if isinstance(result.data, dict) else {}
    animl_path = result_data.get("animl_file_path", "") or result_data.get("AnIMLFilePath", "")

    plate_id = (
        params.get("PlateID") or params.get("plate_id") or params.get("plateId")
        or current_plate_id
    )
    if not plate_id and animl_path:
        # Caller left PlateID empty — recover the id the Tecan bridge actually
        # used from its own filename convention instead of leaving this
        # measurement unlinked to any plate.
        plate_id = _ANIML_TIMESTAMP_SUFFIX_RE.sub('', Path(animl_path).stem)

    if not plate_id:
        return None

    if state is not None:
        state.add_log("info", f"Analysis result linked to plate {plate_id}", "plates")

    if _db is None or not animl_path:
        return plate_id

    protocol_name = params.get("ProtocolFile") or params.get("protocol", "")
    return ingest_animl_measurement(
        plate_id, animl_path,
        device_id=device_id, action=action, protocol_name=protocol_name,
        run_id=run_id, state=state,
    )


def ingest_animl_measurement(
    plate_id: str, animl_path: str, *,
    device_id: str = "tecan", action: str = "RunMeasurement",
    protocol_name: str = "", run_id: Optional[str] = None, state=None,
) -> Optional[str]:
    """Core "parse the measurement and write it into the chemical DB against
    this plate" logic — shared by track_tecan_measurement (a live SiLA2
    result just came back) and attach_existing_measurement (a user picked an
    already-existing .animl file for a plate that was never live-measured
    through this webapp, e.g. read on another PC or from an older run).
    Both paths must write identical instrument_measurements/well rows, so
    this is the single place that does it. Returns plate_id on success (even
    if per-well ingestion partially failed — see the broad except below,
    unchanged from the original inline behavior), None if _db is unavailable.

    Despite the parameter name (kept for the "which file is this measurement
    associated with" DB column, and because both call sites still only know
    an .animl path — the bridge's gRPC response and the file-browser dropdown
    both work in AnIML filenames), the actual parsing prefers the raw Tecan
    XML this AnIML file was generated from (see _resolve_source_path): the
    AnIML conversion step is our own code and has been the source of every
    bug found in this measurement pipeline (Type="Scan" wells silently
    reading 0, missing wavelength axis, ...), while the XML is written
    straight from what the instrument itself produced, never transformed by
    us first. Falls back to parsing the AnIML file itself when no sibling
    XML exists on disk.
    """
    if _db is None:
        return plate_id

    try:
        ensure_plate_for_measurement(plate_id, run_id=run_id)

        source_path = _resolve_source_path(animl_path)
        if source_path.suffix.lower() == ".xml":
            from src.tecan_xml_parser import parse_tecan_xml
            parsed_result = parse_tecan_xml(source_path)
        else:
            from src.animl_parser import parse_animl
            parsed_result = parse_animl(source_path)
        experiment_steps = parsed_result.get("experiment_steps", [])

        protocol_id = None
        first_channel_id = None
        channel_id_by_step_name: Dict[str, Optional[int]] = {}
        if protocol_name:
            proto_data: dict = {}
            for exp_step in experiment_steps:
                proto_data = {
                    "measurement_type": exp_step.get("measurement_type"),
                    "wavelength_nm": exp_step.get("wavelength_nm"),
                    "excitation_nm": exp_step.get("excitation_nm"),
                    "emission_nm": exp_step.get("emission_nm"),
                    "parameters": exp_step.get("parameters"),
                }
                if any(v is not None for v in proto_data.values()):
                    break
            protocol_id = _db.get_or_create_protocol(protocol_name, proto_data)

            # One channel per distinct experiment_step (fixes multi-technique
            # AnIML files collapsing into a single protocol row).
            for idx, exp_step in enumerate(experiment_steps):
                step_name = exp_step.get("step_name") or f"step_{idx}"
                cid = _db.get_or_create_protocol_channel(protocol_id, step_name, {
                    "channel_index": idx,
                    "measurement_type": exp_step.get("measurement_type"),
                    "wavelength_nm": exp_step.get("wavelength_nm"),
                    "excitation_nm": exp_step.get("excitation_nm"),
                    "emission_nm": exp_step.get("emission_nm"),
                    "parameters": exp_step.get("parameters"),
                })
                channel_id_by_step_name[step_name] = cid
                if idx == 0:
                    first_channel_id = cid

        meas_type = experiment_steps[0].get("measurement_type") if experiment_steps else None

        measurement_id = _db.save_instrument_measurement({
            "run_id": run_id,
            "plate_id": plate_id,
            "instrument": device_id,
            "command": action,
            "executed_at": datetime.now().isoformat(),
            "animl_path": animl_path,
            "protocol_name": protocol_name,
            "protocol_id": protocol_id,
            "protocol_channel_id": first_channel_id,
            "measurement_type": meas_type,
        })

        # Per-(measurement signature) cycle counter: repeated experiment_steps
        # with the same technique/wavelength in one AnIML file are treated as
        # successive kinetic-read cycles, in file order.
        cycle_counters: Dict[tuple, int] = {}
        well_values = []
        for idx, exp_step in enumerate(experiment_steps):
            step_name = exp_step.get("step_name") or f"step_{idx}"
            meas_type = exp_step.get("measurement_type")
            wl_nm = exp_step.get("wavelength_nm")
            ex_nm = exp_step.get("excitation_nm")
            em_nm = exp_step.get("emission_nm")
            signature = (meas_type, wl_nm, ex_nm, em_nm)
            cycle_counters[signature] = cycle_counters.get(signature, 0) + 1
            cycle = cycle_counters[signature]
            channel_id = channel_id_by_step_name.get(step_name)
            for m in exp_step.get("measurements", []):
                well_values.append({
                    "well": m.get("well"),
                    "value": m.get("value"),
                    "unit": m.get("unit"),
                    "measurement_type": meas_type,
                    "wavelength_nm": wl_nm,
                    "excitation_nm": ex_nm,
                    "emission_nm": em_nm,
                    "cycle": cycle,
                    "protocol_channel_id": channel_id,
                    "timestamp": datetime.now().isoformat(),
                })
        if well_values:
            _db.save_well_measurements(plate_id, measurement_id, well_values, protocol_id=protocol_id)
            _db.update_plate_status(plate_id, "measured")
    except Exception as exc:
        logger.warning(f"AnIML DB integration failed: {exc}")

    return plate_id


def attach_existing_measurement(
    plate_id: str, animl_filename: str, results_dir: Path, *,
    protocol_name: str = "", state=None,
) -> str:
    """Link an AnIML file that already exists on disk (a measurement run
    outside this webapp's own "Run measurement" flow, or one run earlier and
    never associated with this plate_id) to `plate_id` — the "Attach
    existing result" path in the "Add an analysis to this plate" dialog,
    alongside the pre-existing "Run measurement" (live) path.

    Raises FileNotFoundError if the file doesn't exist, ValueError if it
    resolves outside results_dir/AnIML (same guard as the file-serving
    routes in webapp/app.py) or if _db isn't available. Returns plate_id on
    success — per-well ingestion failures are logged, not raised (matching
    ingest_animl_measurement/track_tecan_measurement's existing behavior:
    a plate row and the measurement row must still end up linked even if a
    later step in the same try block has a problem).
    """
    if _db is None:
        raise ValueError("Database not available")

    animl_dir = results_dir / "AnIML"
    file_path = animl_dir / animl_filename
    # Validate containment BEFORE checking existence - a traversal attempt
    # that happens not to resolve to an existing path must still come back
    # as "invalid filename", not leak into a different error path.
    try:
        file_path.resolve().relative_to(animl_dir.resolve())
    except ValueError:
        raise ValueError("Invalid filename")
    if not file_path.exists():
        raise FileNotFoundError(f"AnIML file not found: {animl_filename}")

    if state is not None:
        state.add_log("info", f"Existing analysis {animl_filename} attached to plate {plate_id}", "plates")

    result = ingest_animl_measurement(
        plate_id, str(file_path),
        device_id="tecan_manual", action="RunMeasurement",
        protocol_name=protocol_name, run_id=None, state=state,
    )
    if result is None:
        raise ValueError("Database not available")
    return result
